test(function()
  local s=Store.Initialize(nil,"A")
  assert(s:SetOption("quality",{quality=0,enabled=true})); assert(s:SetOption("maxStackVendorPrice",1200))
  assert(s:AddRule({id="cheap",scope="SELL",result="JUNK",match="ALL",predicates={{field="unitVendorPrice",op="LT",value=10}}}))
  assert(not s:AddRule({id="bad",scope="BOTH",result="JUNK",match="ALL",predicates={{field="unknown",op="EQ",value=1}}}))
