assert(_VERSION == "Lua 5.1")
local Addon = {}
function Addon.Copy(value)
  if type(value) ~= "table" then return value end
  local result = {}; for key, entry in pairs(value) do result[key] = Addon.Copy(entry) end; return result
end
local chunk=assert(loadfile("src/store/store.lua")); chunk("Dejunk-WotLK", Addon)
local Store = Addon.Store
local passed = 0
local function eq(a,b) assert(a==b,"expected "..tostring(b)..", got "..tostring(a)) end
local function test(fn) fn(); passed=passed+1 end

test(function()
  local s=Store.Initialize(nil,"Realm\31Alice"); eq(s:GetActiveProfileId(),"default")
  eq(s:Serialize().schemaVersion,1); eq(s.mode,"created")
end)
test(function()
  local s=Store.Initialize(nil,"A"); local id=s:CreateProfile("Raid")
  eq(id,"profile-1"); eq(s:GetActiveProfileId(),id); assert(s:RenameProfile(id,"Raid 2"))
  assert(not s:RenameProfile("default","x")); assert(not s:DeleteProfile("default")); assert(not s:ResetProfile("default"))
end)
test(function()
  local s=Store.Initialize(nil,"A"); local id=s:CreateProfile("A")
  s:EditList("profile","inclusions",123,true)
  local copyId=s:CreateProfile("B",id); s:EditList("profile","inclusions",456,true)
  eq(s.state.profiles[copyId].inclusions[456],true); eq(s.state.profiles[id].inclusions[456],nil)
end)
test(function()
  local s=Store.Initialize(nil,"A"); local id=s:CreateProfile("X"); s:AssignCharacter("B",id)
  s:DeleteProfile(id); eq(s.state.characterProfiles.A,"default"); eq(s.state.characterProfiles.B,"default")
end)
test(function()
  local s=Store.Initialize(nil,"A"); local p=s:ImportPreview("global","inclusions","123, 45;123")
  eq(#p.add,2); assert(s:CommitImport(p)); eq(s:ExportList("global","inclusions"),"45\n123")
  local stale=s:ImportPreview("global","inclusions","8"); s:EditList("global","exclusions",9,true)
  local ok,reason=s:CommitImport(stale); assert(not ok); eq(reason,"STALE_PREVIEW")
end)
test(function()
  local s=Store.Initialize(nil,"A")
  assert(not s:ImportPreview("global","inclusions","12|print(1)"))
  assert(not s:ImportPreview("global","inclusions","0"))
  assert(not s:ImportPreview("global","inclusions",string.rep("1",65537)))
end)
test(function()
  local old={schemaVersion=1,profiles={default={name="bad",inclusions={["bad"]=true},options={}}},global={inclusions={[12]=true}}}
  local s=Store.Initialize(old,"A"); eq(s.state.profiles.default.name,"Default"); eq(s.state.profiles.default.inclusions.bad,nil)
  eq(old.profiles.default.name,"bad"); eq(s.state.global.inclusions[12],true)
end)
test(function()
  local saved={schemaVersion=77,profiles={default={name="Future"}}}; local s=Store.Initialize(saved,"A")
  assert(s.readonly); eq(s.mode,"future-readonly"); assert(not s:CreateProfile("x")); assert(not s:EditList("global","inclusions",4,true))
  eq(s:GetActiveProfile().name,"Default"); eq(s:GetState().recovery.schemaVersion,77)
  local serialized,reason=s:Serialize(); eq(serialized,nil); eq(reason,"FUTURE_SCHEMA_READ_ONLY")
end)
test(function()
  local callbacks=0; local s=Store.Initialize(nil,"A"); s:OnChange(function(snapshot) callbacks=callbacks+1; snapshot.global.inclusions[77]=true end)
  s:EditList("global","inclusions",5,true); eq(callbacks,1); eq(s.state.global.inclusions[77],nil)
  local state=s:GetState(); state.global.inclusions[5]=nil; eq(s.state.global.inclusions[5],true)
end)
test(function()
  local account=Store.Initialize(nil,"Realm\\31Tester")
  local id=account:CreateProfile("Test")
  account:EditList("global","inclusions",6948,true)
  local reloaded=Store.Initialize(account:Serialize(),"Realm\\31Tester")
  eq(reloaded:GetActiveProfileId(),id)
  eq(reloaded:GetActiveProfile().name,"Test")
  eq(reloaded.state.global.inclusions[6948],true)
end)
print("STORE RESULT: "..passed.." passed")
